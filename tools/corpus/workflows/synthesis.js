async function mapMidFinal(key, mapTask, midTask, groupSize, finalTask, out) {
  const groups = chunk(plan[key], groupSize)
  const mids = await pipeline(groups,
    async (files, gi) => (await parallel(files.map((f, i) => () => mapAgent(mapTask, f, `${key} #${gi * groupSize + i + 1}`)))).filter(Boolean),
    (parts, _g, gi) => parts.length ? midAgent(midTask, parts, `${key} 中间汇总 ${gi + 1}`) : null)
  return finalAgent(finalTask, mids.filter(Boolean), out, `${key} 最终`)
}


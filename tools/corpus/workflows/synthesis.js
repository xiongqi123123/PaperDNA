const chunk = (arr, k) => { const out = []; for (let i = 0; i < arr.length; i += k) out.push(arr.slice(i, i + k)); return out }
const mapAgent = (task, file, label) => agent(`${GUARD}${task}\n\n批次文件：${file}\n${READ}\n${GROUND}`, { label, phase: 'Map', model: 'sonnet' })
